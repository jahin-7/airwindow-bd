const BN_DIGITS = "০১২৩৪৫৬৭৮৯";
export function toBn(x: number | string): string {
  return String(x).replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)]);
}

export function dict(lang: Lang | null): Dict {
  return lang === "bn" ? bn : en;
}

export function num(lang: Lang | null, x: number, digits = 0): string {
  const s = x.toFixed(digits);
  return lang === "bn" ? toBn(s) : s;
}

/** API times are naive Asia/Dhaka wall-clock strings; format them without timezone conversion. */
export function clock(lang: Lang | null, iso: string): string {
  const h24 = Number(iso.slice(11, 13));
  const h = h24 % 12 === 0 ? 12 : h24 % 12;
  if (lang === "bn") {
    const part = h24 < 6 ? "রাত" : h24 < 12 ? "সকাল" : h24 < 15 ? "দুপুর" : h24 < 18 ? "বিকেল" : h24 < 20 ? "সন্ধ্যা" : "রাত";
    return `${part} ${toBn(h)}টা`;
  }
  return `${h} ${h24 < 12 ? "am" : "pm"}`;
}
